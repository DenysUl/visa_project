def set_run_font(run, size=14, bold=False, italic=False):
    run.font.name = "Times New Roman"
    run.font.size = Pt(size)
    run.bold = bold
    run.italic = italic
    rpr = run._element.get_or_add_rPr()
    rfonts = rpr.get_or_add_rFonts()
    rfonts.set(qn("w:ascii"), "Times New Roman")
    rfonts.set(qn("w:hAnsi"), "Times New Roman")
    rfonts.set(qn("w:cs"), "Times New Roman")
    rfonts.set(qn("w:eastAsia"), "Times New Roman")


def set_paragraph_format(p, *, align, first_line=0, space_before=0, space_after=0,
                         line=1.5, left=0):
    pf = p.paragraph_format
    p.alignment = align
    pf.line_spacing_rule = WD_LINE_SPACING.MULTIPLE if line == 1.5 else WD_LINE_SPACING.SINGLE
    pf.line_spacing = line
    pf.space_before = Pt(space_before)
    pf.space_after = Pt(space_after)
    pf.first_line_indent = Cm(first_line)
    pf.left_indent = Cm(left)
    pf.widow_control = True


def add_text(doc, text, *, align=WD_ALIGN_PARAGRAPH.JUSTIFY, first_line=1.25,
             bold=False, italic=False, size=14, space_before=0, space_after=0,
             line=1.5, left=0):
    p = doc.add_paragraph()
    set_paragraph_format(
        p, align=align, first_line=first_line,
        space_before=space_before, space_after=space_after, line=line, left=left,
    )
    run = p.add_run(text)
    set_run_font(run, size=size, bold=bold, italic=italic)
    return p


def add_heading_chapter(doc, line1, line2):
    add_text(doc, line1, align=WD_ALIGN_PARAGRAPH.CENTER, first_line=0, bold=True)
    add_text(doc, line2, align=WD_ALIGN_PARAGRAPH.CENTER, first_line=0, bold=True, space_after=12)


def add_heading_section(doc, text):
    add_text(doc, text, align=WD_ALIGN_PARAGRAPH.LEFT, first_line=0, bold=True,
             space_before=12, space_after=12)


def add_body(doc, text):
    add_text(doc, text, align=WD_ALIGN_PARAGRAPH.JUSTIFY, first_line=1.25)


def set_cell_shading(cell, fill="D9D9D9"):
    tc_pr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:fill"), fill)
    shd.set(qn("w:val"), "clear")
    tc_pr.append(shd)


def set_cell_border(cell):
    tc_pr = cell._tc.get_or_add_tcPr()
    tc_borders = OxmlElement("w:tcBorders")
    for edge in ("top", "left", "bottom", "right"):
        el = OxmlElement(f"w:{edge}")
        el.set(qn("w:val"), "single")
        el.set(qn("w:sz"), "4")
        el.set(qn("w:space"), "0")
        el.set(qn("w:color"), "000000")
        tc_borders.append(el)
    tc_pr.append(tc_borders)


def write_cell(cell, text, *, bold=False, size=12, align=WD_ALIGN_PARAGRAPH.CENTER):
    cell.text = ""
    p = cell.paragraphs[0]
    p.alignment = align
    pf = p.paragraph_format
    pf.line_spacing = 1.0
    pf.space_before = Pt(2)
    pf.space_after = Pt(2)
    pf.first_line_indent = Cm(0)
    run = p.add_run(text)
    set_run_font(run, size=size, bold=bold)
    set_cell_border(cell)


def add_table_caption(doc, number, title):
    add_text(doc, f"Таблиця {number}", align=WD_ALIGN_PARAGRAPH.RIGHT, first_line=0,
             space_before=12)
    add_text(doc, title, align=WD_ALIGN_PARAGRAPH.CENTER, first_line=0, space_after=6)


def add_table_note(doc, text):
    add_text(doc, text, align=WD_ALIGN_PARAGRAPH.JUSTIFY, first_line=0,
             italic=True, size=12, space_before=6, space_after=12, line=1.0)


def add_table(doc, headers, rows):
    table = doc.add_table(rows=1 + len(rows), cols=len(headers))
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    table.autofit = True
    for i, h in enumerate(headers):
        write_cell(table.rows[0].cells[i], h, bold=True, size=11)
        set_cell_shading(table.rows[0].cells[i], "D9D9D9")
    for r_i, row in enumerate(rows):
        for c_i, val in enumerate(row):
            align = WD_ALIGN_PARAGRAPH.LEFT if c_i == 0 else WD_ALIGN_PARAGRAPH.CENTER
            write_cell(table.rows[r_i + 1].cells[c_i], val, size=11, align=align)
    return table


def add_biblio_item(doc, number, text):
    p = doc.add_paragraph()
    set_paragraph_format(
        p, align=WD_ALIGN_PARAGRAPH.JUSTIFY, first_line=-0.75, line=1.5, left=0.75,
    )
    run = p.add_run(f"{number}. {text}")
    set_run_font(run, size=14)


def set_page_number(doc):
    footer = doc.sections[0].footer
    footer.is_linked_to_previous = False
    p = footer.paragraphs[0]
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run1 = p.add_run()
    set_run_font(run1, size=14)
    fld1 = OxmlElement("w:fldChar")
    fld1.set(qn("w:fldCharType"), "begin")
    run1._r.append(fld1)
    run2 = p.add_run()
    set_run_font(run2, size=14)
    instr = OxmlElement("w:instrText")
    instr.set(qn("xml:space"), "preserve")
    instr.text = " PAGE "
    run2._r.append(instr)
    run3 = p.add_run()
    set_run_font(run3, size=14)
    fld2 = OxmlElement("w:fldChar")
    fld2.set(qn("w:fldCharType"), "end")
    run3._r.append(fld2)


def prevent_table_break(table):
    for row in table.rows:
        tr_pr = row._tr.get_or_add_trPr()
        cant = OxmlElement("w:cantSplit")
        tr_pr.append(cant)


